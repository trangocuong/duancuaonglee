import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { utils, write } from 'xlsx/xlsx.mjs';
import { summarizeSeeLotWorkbook } from './engine/lot-tracker.js';
import { connectRunMaps } from '../outputs/LOT-Tracker-Offline-Windows-x64/run-maps.mjs';
import { trackingLists } from '../outputs/LOT-Tracker-Offline-Windows-x64/tracking.mjs';
const headers = ['NO', 'REPRSN_SRLNO', 'LOT_ID', 'BARCODE_SERLNO', 'PROD_ID', 'SPLIT_LOT', 'RESERVE_ID', 'PS_PROC', 'FW_PROC', 'TEST_RESULT', 'PCB_ARRAY', 'MERGE_LOT', 'PCB_MAP', 'WORK_NAME', 'FRONT_RESULT', 'BACK_RESULT', 'FRONT_SCRAP_CODE', 'BACK_SCRAP_CODE', 'CREATE_DATE'];
const row = (n, target) => [n, 'BAR-' + n, 'RUN-A', 'BAR-' + n, 'PART-A', 'CHILD-' + n, '', 0, 0, '', 3, target, '', '', '', '', '', '', '20260922 100000'];
const rows = Array.from({ length: 400 }, (_, i) => row(i + 1, i % 2 ? 'LOT-A' : 'LOT-B'));
const book = utils.book_new(); utils.book_append_sheet(book, utils.aoa_to_sheet([headers, ...rows]), 'Sheet1');
const bytes = write(book, { type: 'buffer', bookType: 'biff8' });
const map = summarizeSeeLotWorkbook(bytes, 'RUN-A.xls');
assert.equal(map.mapRecords.length, 400);
assert.equal(new Set(map.mapRecords.map(r => r.mergeLot)).size, 2);
assert.equal(map.currentQty, '');
assert.deepEqual(map.relations, [], 'Metadata must not create process events');
const event = (lotId, origin) => ({ lotId, originSplitLotIds: [origin], relations: [], partNumber: '', steps: { M010: [], M015: [], M033: [] } });
const summaries = [event('LOT-A', 'RUN-A'), event('LOT-B', 'RUN-A'), event('DESCENDANT', 'LOT-A'), event('UNRELATED', 'OTHER')];
const links = connectRunMaps(summaries, [map]);
assert.equal(links.linkedLots, 3);
assert.equal(summaries[0].partNumber, 'PART-A');
assert.equal(summaries[2].runMapLinks[0].type, '원본 경유 연결');
assert.equal(summaries[3].partNumber, '');
assert.equal(trackingLists(summaries, [map]).missing.length, 0);
assert.equal(trackingLists([event('LOT-A', 'RUN-A')], [map]).matrices['SMT RUNID 추적'][1][4], 'RUNID 미확인');
const conflict = { ...map, lotId: 'RUN-B', mapRecords: map.mapRecords.map(r => ({ ...r, productId: 'PART-B' })) };
const uncertain = [event('DESCENDANT', 'LOT-A')];
connectRunMaps(uncertain, [map, conflict]);
assert.equal(uncertain[0].partNumber, '', 'Conflicting map products must stay unknown');
const missingHistory = [event('DESCENDANT', 'LOT-A')]; missingHistory[0].steps = {};
connectRunMaps(missingHistory, [map]);
assert.ok(trackingLists(missingHistory, [map]).missing.some(r => r.id === 'LOT-A'));
const fixture = path.resolve('outputs/run-map-test'); fs.mkdirSync(fixture, { recursive: true });
const mapPath = path.join(fixture, 'RUN-A.xls'); fs.writeFileSync(mapPath, bytes);
const eventPath = path.join(fixture, 'LOT-A.csv');
fs.writeFileSync(eventPath, 'EVENT_NAME,DATE/TIME,QTY,STEP,EQP,LINE,OPERID,CHG_ITEM,CHG_VALS,QTY,COMMENT\nTrackOut,2026-09-22 12:00,3,M015,EQP-2,L1,U,,,0,\nTrackIn,2026-09-22 11:00,3,M010,EQP-1,L1,U,,,0,\nSplit,2026-09-22 10:00,3,M010,,L1,U,,RUN-A,3,\n');
const app = path.resolve('outputs/LOT-Tracker-Offline-Windows-x64');
function run(files) { return spawnSync(path.join(app, 'runtime/node.exe'), ['--permission', '--allow-fs-read=*', '--allow-fs-write=' + fixture, path.join(app, 'analyze.mjs')], { input: JSON.stringify({ files, output: path.join(fixture, 'reports') }), encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }); }
const complete = run([eventPath, mapPath]); assert.equal(complete.status, 0, complete.stderr);
const result = JSON.parse(complete.stdout); assert.equal(result.count, 1); assert.equal(result.mapCount, 1);
assert.equal(result.tabs[0].rows[2][0], 'PART-A');
assert.notEqual(run([mapPath]).status, 0, 'Map-only input must ask for event history');
console.log('PASS: 400-row XLS with multiple merges, direct/indirect/unlinked/conflicting mapping, no fabricated process totals, map-only error, and offline engine integration.');
