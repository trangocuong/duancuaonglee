import {build} from 'esbuild';
import fs from 'node:fs';
import {buildDarkTheme} from './dark-theme.mjs';
const client = await build({entryPoints:['evaluation/client.tsx'],bundle:true,write:false,outdir:'evaluation/generated',format:'esm',minify:true,jsx:'automatic',target:'es2022',loader:{'.css':'css'}});
fs.mkdirSync('evaluation/generated',{recursive:true});
const js=client.outputFiles.find(f=>f.path.endsWith('.js')).text, lightCss=client.outputFiles.find(f=>f.path.endsWith('.css')).text, css=lightCss+buildDarkTheme(lightCss);
const template=fs.readFileSync('evaluation/public/evaluation-report-template.xlsx').toString('base64');
fs.writeFileSync('evaluation/generated/assets.js',`// Generated by pnpm build:evaluation.\nexport const clientJs=${JSON.stringify(js)};\nexport const clientCss=${JSON.stringify(css)};\nexport const reportTemplate=${JSON.stringify(template)};\n`);
await build({entryPoints:['evaluation/server.ts'],bundle:true,outfile:'evaluation/generated/server.js',format:'esm',platform:'neutral',target:'es2022',minify:true});
console.log('Q-EVAL client and API built.');
